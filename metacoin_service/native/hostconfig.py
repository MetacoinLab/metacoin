"""Second-host configuration generator and checker (order 2026-10-23 §14). It writes the files an operator on ANOTHER host needs
to run a provider against a settlement domain, or a second settlement domain peered with the first, and checks them without
touching any network: distinct ports, TLS for anything beyond loopback, a signer per economic party, no key material in the
files. Generating a configuration is not a deployment: real second-host behaviour stays unverified until the operator of that
host runs the printed self-check against the real service (`metacoin-provider --home DIR handshake`).

    python -m metacoin_service.native.hostconfig generate --role provider --service-url https://host-a.example:8443 --ca ca.pem --domain dom-a --out ./host-b
    python -m metacoin_service.native.hostconfig generate --role domain --domain-id dom-b --peer-url https://host-a.example:8443 --peer-domain dom-a --out ./host-b-domain
    python -m metacoin_service.native.hostconfig check ./host-b"""
import argparse
import json
import os
import sys
from urllib.parse import urlparse


def generate(a):
    os.makedirs(a.out, exist_ok=True); u = urlparse(a.service_url or a.peer_url or 'http://127.0.0.1:8402'); loopback = u.hostname in ('127.0.0.1', 'localhost', '::1')
    if not loopback and u.scheme != 'https':
        print(json.dumps({'error': 'plain_http_off_loopback', 'note': 'the service URL is not loopback: use https and pass --ca; the client refuses plain http elsewhere'})); return 2
    files = {}
    if a.role == 'provider':
        files['provider.env'] = '\n'.join(['# provider host environment (no secrets here; the credential and signer token live in 0600 files)', 'METACOIN_BASE=%s' % a.service_url, 'METACOIN_CA=%s' % (a.ca or ''), 'METACOIN_DOMAIN=%s' % a.domain, 'METACOIN_SIGNER_URL=http://127.0.0.1:%d' % a.signer_port, 'METACOIN_SIGNER_TOKEN_FILE=%s/signer/token' % os.path.abspath(a.out), 'METACOIN_X402_DISABLED=1', ''])
        files['run-signer.sh'] = '#!/usr/bin/env bash\n# operator-controlled signer for THIS provider\'s keys; loopback only; never exposed\nset -eu\nH="$(dirname "$0")/signer"\n[ -f "$H/token" ] || python -m metacoin_service.native.signer init --home "$H" --domains %s --signer-id %s\nexec python -m metacoin_service.native.signer serve --home "$H" --port %d\n' % (a.domain, a.signer_id, a.signer_port)
        files['enroll.sh'] = '#!/usr/bin/env bash\n# one-time: enroll this provider through the service administrator (admin credential supplied out of band) and initialise the pinned client home\nset -eu\nD="$(dirname "$0")"; . "$D/provider.env"\nmetacoin-provider --base "$METACOIN_BASE" ${METACOIN_CA:+--ca "$METACOIN_CA"} --signer "$METACOIN_SIGNER_URL" --signer-token "$METACOIN_SIGNER_TOKEN_FILE" enroll --admin-cred "$1" --name %s --ceiling %d --out "$D/provider-cred.json"\nmetacoin-provider --base "$METACOIN_BASE" ${METACOIN_CA:+--ca "$METACOIN_CA"} --cred "$D/provider-cred.json" --home "$D/home" --signer "$METACOIN_SIGNER_URL" --signer-token "$METACOIN_SIGNER_TOKEN_FILE" --actor %s init --provider-name %s\n' % (a.name, a.ceiling, a.name, a.name)
        files['selfcheck.sh'] = '#!/usr/bin/env bash\n# run on the provider host after enroll.sh: pins and versions must match; prints JSON\nset -eu\nD="$(dirname "$0")"; . "$D/provider.env"\nmetacoin-provider --home "$D/home" handshake\nmetacoin-provider conformance\n'
        files['identity.json'] = json.dumps({'relationship': 'independent_declared', 'identity': {'operator_id': a.operator, 'machine_id': a.machine, 'worker_instance': a.name + '-w1', 'signer_id': a.signer_id, 'domain': a.domain}, 'note': 'declared by the provider; the service discloses shared operators and never counts a declaration as independence'}, indent=1)
    else:
        files['domain.env'] = '\n'.join(['# second settlement domain (operator B) — API beyond loopback must run with --tls', 'METACOIN_HOME=%s/home' % os.path.abspath(a.out), 'METACOIN_DOMAIN_ID=%s' % a.domain_id, 'METACOIN_PEER_URL=%s' % a.peer_url, 'METACOIN_PEER_DOMAIN=%s' % a.peer_domain, 'METACOIN_X402_DISABLED=1', 'METACOIN_FACILITATOR_URL=http://127.0.0.1:1/blocked', 'METACOIN_REQUIRE_EXTERNAL_CUSTODY=1', ''])
        files['up.sh'] = '#!/usr/bin/env bash\n# API + worker + signer + witness on this host (deploy_local); then pin the peer authority from a value obtained OUT OF BAND\nset -eu\nD="$(dirname "$0")"; . "$D/domain.env"\npython -m metacoin_service.deploy_local up --home "$METACOIN_HOME" --domain-id "$METACOIN_DOMAIN_ID" --port %d\necho "now: POST /api/v1/native/peers with the peer authority key id / public hex / epoch read from the peer operator (not from the network)"\n' % a.port
        files['selfcheck.sh'] = '#!/usr/bin/env bash\nset -eu\nD="$(dirname "$0")"; . "$D/domain.env"\npython -m metacoin_service.deploy_local status --home "$METACOIN_HOME"\n'
    files['README.txt'] = 'Generated by metacoin_service.native.hostconfig for role %s. Nothing here is a credential. Real second-host behaviour is unverified until selfcheck.sh runs on that host against the real service over TLS.\n' % a.role
    for name, body in files.items():
        p = os.path.join(a.out, name)
        with open(p, 'w') as f:
            f.write(body)
        os.chmod(p, 0o755 if name.endswith('.sh') else 0o644)
    print(json.dumps({'role': a.role, 'out': os.path.abspath(a.out), 'files': sorted(files), 'service_loopback': loopback, 'tls_required': not loopback})); return 0


def check(a):
    problems = []; files = os.listdir(a.dir) if os.path.isdir(a.dir) else []
    if not files:
        print(json.dumps({'ok': False, 'problems': ['no_files']})); return 1
    env = {}
    for name in ('provider.env', 'domain.env'):
        p = os.path.join(a.dir, name)
        if os.path.exists(p):
            for line in open(p):
                if '=' in line and not line.startswith('#'):
                    k, v = line.strip().split('=', 1); env[k] = v
    url = env.get('METACOIN_BASE') or env.get('METACOIN_PEER_URL')
    if url:
        u = urlparse(url); loop = u.hostname in ('127.0.0.1', 'localhost', '::1')
        if not loop and u.scheme != 'https':
            problems.append('service_url_plain_http_off_loopback')
        if not loop and 'METACOIN_CA' in env and not env['METACOIN_CA']:
            problems.append('ca_missing_for_tls')
    ports = [int(env[k].rsplit(':', 1)[1]) for k in env if k.endswith('_URL') and env[k].rsplit(':', 1)[-1].isdigit()]
    if len(ports) != len(set(ports)):
        problems.append('duplicate_ports')
    for name in files:
        p = os.path.join(a.dir, name)
        if os.path.isfile(p):
            body = open(p, 'rb').read()
            if b'BEGIN PRIVATE KEY' in body or b'AGE-SECRET-KEY' in body or b'private_key_hex' in body:
                problems.append('key_material_in_' + name)
            if name.endswith('.sh') and not os.access(p, os.X_OK):
                problems.append('not_executable_' + name)
    print(json.dumps({'ok': not problems, 'problems': problems, 'files': sorted(files), 'note': 'static check only; real second-host behaviour unverified until selfcheck.sh runs there'})); return 0 if not problems else 1


def main(argv=None):
    ap = argparse.ArgumentParser(prog='metacoin-hostconfig'); sub = ap.add_subparsers(dest='cmd', required=True)
    g = sub.add_parser('generate'); g.add_argument('--role', choices=('provider', 'domain'), required=True); g.add_argument('--out', required=True); g.add_argument('--service-url'); g.add_argument('--ca'); g.add_argument('--domain', default='dom-a'); g.add_argument('--name', default='prov-b'); g.add_argument('--ceiling', type=int, default=1000)
    g.add_argument('--signer-id', default='signer-b'); g.add_argument('--signer-port', type=int, default=9440); g.add_argument('--operator', default='operator-b'); g.add_argument('--machine', default='rig-b'); g.add_argument('--domain-id', default='dom-b'); g.add_argument('--peer-url'); g.add_argument('--peer-domain', default='dom-a'); g.add_argument('--port', type=int, default=8412)
    c = sub.add_parser('check'); c.add_argument('dir'); a = ap.parse_args(argv)
    return generate(a) if a.cmd == 'generate' else check(a)


if __name__ == '__main__':
    sys.exit(main())
